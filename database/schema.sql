-- Run this file once in the Supabase SQL Editor for the project configured in .env.local.
-- The service-role key stays on the server and is never sent to the browser.

create table if not exists public.site_state (
  id smallint primary key check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  customer_name text not null default '',
  customer_phone text not null,
  fulfillment_method text not null check (fulfillment_method in ('delivery', 'pickup')),
  delivery_address text,
  items jsonb not null,
  subtotal numeric(10, 2) not null default 0,
  discount numeric(10, 2) not null default 0,
  delivery_fee numeric(10, 2) not null default 0,
  total numeric(10, 2) not null default 0,
  coupon_code text,
  status text not null default 'new' check (status in ('new', 'preparing', 'ready', 'completed', 'cancelled')),
  created_at timestamptz not null default now()
);

-- Safe for projects where the orders table was created before customer names were stored.
alter table public.orders add column if not exists customer_name text not null default '';

create index if not exists orders_created_at_desc_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);

alter table public.site_state enable row level security;
alter table public.orders enable row level security;

revoke all on public.site_state from anon, authenticated;
revoke all on public.orders from anon, authenticated;
grant all on public.site_state to service_role;
grant all on public.orders to service_role;
grant usage, select on sequence public.orders_id_seq to service_role;
